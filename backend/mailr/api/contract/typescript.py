"""TypeScript types from the typed routes' OpenAPI document (backend/README.md, "Typed API contract").

    python -m mailr.api.contract.typescript OPENAPI_JSON            print the TypeScript
    python -m mailr.api.contract.typescript OPENAPI_JSON --write TS write it (tools/api-types does)
    python -m mailr.api.contract.typescript OPENAPI_JSON --check TS exit 1 when TS is out of date

One interface per schema (a list or union schema becomes a type alias), and `TypedRoutes`, the
success answer of each typed operation by path and method. It reads only what Pydantic writes
(objects, arrays, anyOf, enums and constants, $ref, maps) and fails on anything else, so a new
kind of schema is noticed here instead of turning silently into `unknown`.
"""

from __future__ import annotations

import json
import re
import sys
from typing import Any

HEADER = """// Generated by tools/api-types from frontend/src/api/openapi.json (backend mailr/api/contract).
// Do not edit: change the response model, then run tools/api-types.
"""

_IDENT = re.compile(r"^[A-Za-z_$][A-Za-z0-9_$]*$")


class Unsupported(ValueError):
    pass


def _name(ref: str) -> str:
    return ref.rsplit("/", 1)[1]


def _lit(v: Any) -> str:
    return json.dumps(v, ensure_ascii=False)


_META = {"title", "description", "default", "examples", "deprecated"}


def ts_type(s: dict[str, Any], indent: str = "") -> str:
    if not set(s) - _META:  # Any
        return "unknown"
    if "$ref" in s:
        return _name(s["$ref"])
    if "const" in s:
        return _lit(s["const"])
    if "enum" in s:
        return " | ".join(_lit(v) for v in s["enum"])
    if "anyOf" in s or "oneOf" in s:
        parts: list[str] = []
        for sub in s.get("anyOf") or s.get("oneOf") or []:
            t = ts_type(sub, indent)
            if t not in parts:
                parts.append(t)
        # null last, as written by hand
        parts.sort(key=lambda t: t == "null")
        return " | ".join(f"({p})" if " | " in p and p != parts[-1] and "{" not in p else p for p in parts)
    t = s.get("type")
    if isinstance(t, list):
        return " | ".join(ts_type({**s, "type": x}, indent) for x in t)
    if t == "string":
        return "string"
    if t in ("integer", "number"):
        return "number"
    if t == "boolean":
        return "boolean"
    if t == "null":
        return "null"
    if t == "array":
        inner = ts_type(s.get("items") or {}, indent)
        return f"({inner})[]" if " | " in inner else f"{inner}[]"
    if t == "object" or "properties" in s or "additionalProperties" in s:
        if "properties" in s:
            return _object(s, indent)
        extra = s.get("additionalProperties")
        if extra is True or extra is None or extra == {}:
            return "Record<string, unknown>"
        return f"Record<string, {ts_type(extra, indent)}>"
    raise Unsupported(f"schema not supported: {json.dumps(s)[:200]}")


def _doc(text: str | None, indent: str) -> list[str]:
    if not text:
        return []
    lines = text.strip().splitlines()
    if len(lines) == 1:
        return [f"{indent}/** {lines[0]} */"]
    return [f"{indent}/**", *[f"{indent} * {ln}".rstrip() for ln in lines], f"{indent} */"]


def _object(s: dict[str, Any], indent: str) -> str:
    inner = indent + "  "
    req = set(s.get("required") or [])
    out = ["{"]
    for key, prop in (s.get("properties") or {}).items():
        out += _doc(prop.get("description"), inner)
        k = key if _IDENT.match(key) else _lit(key)
        out.append(f"{inner}{k}{'' if key in req else '?'}: {ts_type(prop, inner)}")
    out.append(f"{indent}}}")
    return "\n".join(out)


def render(doc: dict[str, Any]) -> str:
    schemas = doc.get("components", {}).get("schemas", {})
    out = [HEADER]
    for name in sorted(schemas):
        s = schemas[name]
        out += _doc(s.get("description"), "")
        if s.get("type") == "object" or "properties" in s:
            out.append(f"export interface {name} {_object(s, '')}\n")
        else:
            out.append(f"export type {name} = {ts_type(s)}\n")
    out.append("/** The success answer of each typed operation. */")
    out.append("export interface TypedRoutes {")
    for path in sorted(doc.get("paths") or {}):
        ops = []
        for method, op in sorted(doc["paths"][path].items()):
            for code, resp in sorted((op.get("responses") or {}).items()):
                schema = (resp.get("content") or {}).get("application/json", {}).get("schema")
                if code.startswith("2") and schema:
                    ops.append(f"    {method}: {ts_type(schema, '    ')}")
                    break
        if ops:
            out.append(f"  {_lit(path)}: {{")
            out += ops
            out.append("  }")
    out.append("}")
    return "\n".join(out) + "\n"


def main(argv: list[str]) -> int:
    if not argv:
        print(__doc__, file=sys.stderr)
        return 2
    with open(argv[0], encoding="utf-8") as f:
        text = render(json.load(f))
    if len(argv) == 3 and argv[1] == "--write":
        with open(argv[2], "w", encoding="utf-8") as f:
            f.write(text)
        return 0
    if len(argv) == 3 and argv[1] == "--check":
        try:
            with open(argv[2], encoding="utf-8") as f:
                current = f.read()
        except FileNotFoundError:
            current = ""
        if current != text:
            print(f"{argv[2]} is out of date: run tools/api-types", file=sys.stderr)
            return 1
        return 0
    sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
