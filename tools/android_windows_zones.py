#!/usr/bin/env python3
"""The Windows → IANA zone table for the Android app, from the server's own source.

Outlook and Exchange write Windows zone names ("Central Standard Time"); java.time's ZoneId.of
throws on them. The server maps them with icalendar's table (backend/mailr/calendar/tz.py `iana`);
this writes the same table, each value as the IANA key Python's zoneinfo gives, to
android/app/src/main/java/io/github/murtazanasir/mailr/data/cal/WindowsZones.kt, which Zones.kt reads.

    tools/android_windows_zones.py           write WindowsZones.kt
    tools/android_windows_zones.py --check   change nothing; exit 1 when WindowsZones.kt is out of date

tools/generate runs it (and --check under tools/generate --check).
"""

from __future__ import annotations

import sys
from pathlib import Path
from zoneinfo import ZoneInfo

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "android/app/src/main/java/io/github/murtazanasir/mailr/data/cal/WindowsZones.kt"


def render() -> str:
    from icalendar.timezone.windows_to_olson import WINDOWS_TO_OLSON

    rows = []
    for win, olson in sorted(WINDOWS_TO_OLSON.items()):
        try:
            key = ZoneInfo(olson).key
        except Exception:  # noqa: BLE001  a name this tz database lacks: left out
            continue
        rows.append(f'    "{win}" to "{key}",')
    return (
        "// Generated by tools/android_windows_zones.py from the server's table (icalendar's\n"
        "// windows_to_olson). Do not edit; run tools/generate.\n"
        "package io.github.murtazanasir.mailr.data.cal\n\n"
        "/** Windows zone names (Outlook, Exchange) → IANA ids. */\n"
        "internal val WINDOWS_ZONES: Map<String, String> = mapOf(\n"
        + "\n".join(rows)
        + "\n)\n"
    )


def main() -> int:
    text = render()
    if "--check" in sys.argv[1:]:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT.relative_to(ROOT)} is out of date: run tools/generate", file=sys.stderr)
            return 1
        return 0
    if not OUT.exists() or OUT.read_text() != text:
        OUT.write_text(text)
        print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
