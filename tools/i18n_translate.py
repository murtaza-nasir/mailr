#!/usr/bin/env python3
"""Translate mailr's English catalogues with a model (site/docs/admin/languages.md).

Sources (English):
- web      frontend/src/locales/en.json (without `serverText.*`, a copy of the server's texts)
- server   backend/mailr/i18n/en.json
- android  android/<module>/src/main/res/values/strings*.xml (without strings_server.xml, which
           tools/i18n_server_texts.py generates from the server catalogue)

Outputs, per language (tools/i18n/glossary.json lists them):
- frontend/src/locales/<lang>.json, backend/mailr/i18n/<lang>.json,
- android/<module>/src/main/res/values-<qualifier>/strings*.xml,
- then tools/i18n_server_texts.py copies the translated server texts into the apps.

The cache, tools/i18n/cache/<lang>.json, keeps each translation keyed by surface and key with a
hash of its English, so a rerun asks the model only for new or changed texts. A text someone fixed
by hand in an output file is taken into the cache as `manual` at the next run and never replaced.
A text that fails the checks three times stays English (`english`) and is listed.

    tools/i18n_translate.py                    translate what is new or changed, all languages
    tools/i18n_translate.py --lang de,fr       some languages
    tools/i18n_translate.py --check            no model: exit 1 when a text is missing or stale
    tools/i18n_translate.py --offline          no model: fill new texts with English (pending)
    tools/i18n_translate.py --write            no model: rewrite the outputs from the cache

The model is any OpenAI-compatible endpoint: --endpoint / MAILR_I18N_ENDPOINT (required to translate,
for example http://localhost:8000/v1), --model / MAILR_I18N_MODEL (default: the first one it serves),
MAILR_I18N_API_KEY when the endpoint needs one (never printed).
"""

