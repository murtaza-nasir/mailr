ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import i18n_server_texts as servertexts  # noqa: E402

GLOSSARY_FILE = ROOT / "tools/i18n/glossary.json"
CACHE_DIR = ROOT / "tools/i18n/cache"
WEB_EN = ROOT / "frontend/src/locales/en.json"
SERVER_EN = ROOT / "backend/mailr/i18n/en.json"
ANDROID = ROOT / "android"
ANDROID_MODULES = ("app", "notes", "notes-core", "session-core")
ANDROID_SKIP = {"strings_server.xml"}
PLURAL = re.compile(r"_(zero|one|two|few|many|other)$")
CATEGORIES = ("zero", "one", "two", "few", "many", "other")
OUT_HEADER = "Generated by tools/i18n_translate.py from the English values/ file. Hand edits are kept."

GLOSSARY: dict[str, Any] = json.loads(GLOSSARY_FILE.read_text(encoding="utf-8"))
LANGS: dict[str, dict[str, Any]] = GLOSSARY["languages"]
KEEP: list[str] = sorted(GLOSSARY["keep"], key=len, reverse=True)


# ---------------------------------------------------------------------------- units

@dataclass
class Unit:
    """One text to translate: a plain string, or the forms of a plural."""

    surface: str  # web | server | android
    key: str  # "mail.reader.reply", or "<module>:<file>:<name>" on Android
    en: str | dict[str, str]
    cache_key: str = ""
    sha: str = ""

    def __post_init__(self) -> None:
        self.cache_key = f"{self.surface}:{self.key}" if self.surface != "android" else f"android:{self.key.split(':', 2)[0]}:{self.key.split(':', 2)[2]}"
        self.sha = hashlib.sha256(json.dumps(self.en, sort_keys=True, ensure_ascii=False).encode()).hexdigest()[:16]

    @property
    def plural(self) -> bool:
        return isinstance(self.en, dict)

    def texts(self) -> list[str]:
        return list(self.en.values()) if isinstance(self.en, dict) else [self.en]


def flatten(d: dict, prefix: str = "") -> dict[str, str]:
    out: dict[str, str] = {}
    for k, v in d.items():
        if isinstance(v, dict):
            out.update(flatten(v, f"{prefix}{k}."))
        else:
            out[f"{prefix}{k}"] = str(v)
    return out


def json_units(surface: str, tree: dict, skip_prefix: str | None = None) -> list[Unit]:
    flat = flatten(tree)
    units: list[Unit] = []
    seen: set[str] = set()
    for k, v in flat.items():
        if skip_prefix and k.startswith(skip_prefix):
            continue
        m = PLURAL.search(k)
        if not m:
            units.append(Unit(surface, k, v))
            continue
        base = PLURAL.sub("", k)
        if base in seen:
            continue
        seen.add(base)
        forms = {c: flat[f"{base}_{c}"] for c in CATEGORIES if f"{base}_{c}" in flat}
        units.append(Unit(surface, base, forms))
    return units


def android_files() -> list[Path]:
    out = []
    for mod in ANDROID_MODULES:
        for p in sorted((ANDROID / mod / "src/main/res/values").glob("strings*.xml")):
            if p.name not in ANDROID_SKIP:
                out.append(p)
    return out


def android_decode(s: str) -> str:
    """The text an Android string resource shows (escapes resolved)."""
    if len(s) >= 2 and s[0] == '"' and s[-1] == '"':
        s = s[1:-1]
    out, i = [], 0
    while i < len(s):
        c = s[i]
        if c == "\\" and i + 1 < len(s):
            n = s[i + 1]
            out.append({"n": "\n", "t": "\t"}.get(n, n))
            i += 2
            continue
        out.append(c)
        i += 1
    return "".join(out)


def android_units() -> list[Unit]:
    units: list[Unit] = []
    for p in android_files():
        mod = p.parts[-6]
        for e in ET.parse(p).getroot():
            if not isinstance(e.tag, str) or e.get("translatable") == "false":
                continue
            name = e.get("name")
            if e.tag == "string":
                if len(e):
                    raise SystemExit(f"{p}: {name} has markup; the tool handles plain strings only")
                units.append(Unit("android", f"{mod}:{p.name}:{name}", android_decode(e.text or "")))
            elif e.tag == "plurals":
                units.append(Unit("android", f"{mod}:{p.name}:{name}",
                                  {i.get("quantity"): android_decode(i.text or "") for i in e}))
            else:
                raise SystemExit(f"{p}: <{e.tag} name={name}> is not handled")
    return units


def load_units(surfaces: list[str]) -> list[Unit]:
    units: list[Unit] = []
    if "web" in surfaces:
        units += json_units("web", json.loads(WEB_EN.read_text(encoding="utf-8")), skip_prefix=f"{servertexts.WEB_PREFIX}.")
    if "server" in surfaces:
        units += json_units("server", json.loads(SERVER_EN.read_text(encoding="utf-8")))
    if "android" in surfaces:
        units += android_units()
    return units


# ---------------------------------------------------------------------------- checks

BRACES = re.compile(r"\{\{\s*\w+\s*\}\}")
TAGS = re.compile(r"</?\w+\s*/?>")
FORMATS = re.compile(r"%(?:%|(?:\d+\$)?[-#+0,(]*\d*(?:\.\d+)?[sdfxXcbBeEgGhHoaAtT])")
URLS = re.compile(r"https?://\S+|\b[\w.-]+@[\w-]+\.[\w.]+")
CODE = re.compile(r"`[^`]+`")
CJK = re.compile(r"[㐀-鿿]")
CYRILLIC = re.compile(r"[Ѐ-ӿ]")
LETTERS = re.compile(r"[^\W\d_]", re.UNICODE)
# English words that never appear in German, Spanish, French or Portuguese text.
ENGLISH_WORDS = {"the", "and", "your", "you", "with", "this", "that", "from", "have", "been", "which",
                 "would", "should", "could", "there", "their", "when", "what", "into", "only", "these",
                 "those", "here", "can't", "don't", "isn't", "won't", "couldn't", "doesn't", "it's"}


def marks(s: str, surface: str) -> list[str]:
    """The placeholders and markup a text must keep."""
    found = [re.sub(r"\s", "", m) for m in BRACES.findall(s)] + [re.sub(r"\s", "", m) for m in TAGS.findall(s)]
    if surface == "android":
        found += FORMATS.findall(s)
    found += URLS.findall(s) + CODE.findall(s)
    return sorted(found)


def strip_keep(s: str) -> str:
    """The text without placeholders, markup, URLs, code and the names that stay as they are."""
    s = BRACES.sub(" ", s)
    s = TAGS.sub(" ", s)
    s = FORMATS.sub(" ", s)
    s = URLS.sub(" ", s)
    s = CODE.sub(" ", s)
    for k in KEEP:
        s = re.sub(rf"(?<![\w]){re.escape(k)}(?![\w])", " ", s)
    return s


def words(s: str) -> list[str]:
    """The words of a text, without search operators (from:alice, is:read) and the kept names."""
    body = re.sub(r"\S*:\S+", " ", strip_keep(s))
    return [w for w in re.findall(r"[^\W\d_][^\W\d_']*", body) if re.fullmatch(r"[A-Za-z']+", w) and len(w) > 1]


def needs_model(u: Unit) -> bool:
    """False for texts with nothing to translate (a name, a placeholder or two, punctuation)."""
    for t in u.texts():
        if LETTERS.search(strip_keep(t)):
            return True
        if len(BRACES.findall(t)) >= 2 or len(FORMATS.findall(t)) >= 2:
            return True  # the order of the values may change
    return False


def is_label(s: str) -> bool:
    return len(s) <= 24 and len(s.split()) <= 3 and not s.rstrip().endswith((".", "?", "!", ":"))


def reference(u: Unit, lang: str, form: str) -> str:
    """The English text a translated form is checked against."""
    en = u.en
    assert isinstance(en, dict)
    if form in en and (form != "one" or lang in ("de", "es")):
        return en[form]
    return en.get("other") or next(iter(en.values()))


def check_text(u: Unit, lang: str, src: str, out: Any, form: str | None = None) -> list[str]:
    if not isinstance(out, str) or not out.strip():
        return ["empty or not a string"]
    errs: list[str] = []
    want, got = marks(src, u.surface), marks(out, u.surface)
    if form == "one" and lang in ("de", "es"):
        drop = {"{{count}}"} | ({m for m in want if m.startswith("%") and m.endswith("d")} if u.surface == "android" else set())
        want = [m for m in want if m not in drop]
        got = [m for m in got if m not in drop]
    if want != got:
        errs.append(f"placeholders/markup differ: English has {want or 'none'}, yours has {got or 'none'}")
    if u.surface == "android":
        seq = lambda s: [m for m in FORMATS.findall(s) if "$" not in m and m != "%%"]  # noqa: E731
        if len(seq(src)) > 1 and seq(src) != seq(out):
            errs.append("keep the unnumbered format specifiers in the English order")
    if src.count("\n") != out.count("\n"):
        errs.append("keep the same line breaks as the English")
    body = strip_keep(out)
    # Ordinary words (not names or acronyms) the English has: those must come out in the script.
    plain = [w for w in words(src) if w.islower() and len(w) > 2]
    if lang == "zh-Hans" and len(plain) >= 2 and not CJK.search(body):
        errs.append("not translated into Chinese")
    if lang == "ru" and len(plain) >= 2 and not CYRILLIC.search(body):
        errs.append("not translated into Russian")
    leftover = [w for w in words(out) if w.lower() in ENGLISH_WORDS]
    if leftover:
        errs.append(f"English words left: {', '.join(sorted(set(leftover)))}")
    if lang in ("ru", "zh-Hans"):
        latin = [w for w in words(out) if len(w) > 3 and w.islower() and w in words(src)]
        if len(latin) >= 2:
            errs.append(f"English words left: {', '.join(sorted(set(latin)))}")
    first_src, first_out = src.lstrip()[:1], out.lstrip()[:1]
    starts_with_name = any(out.lstrip().startswith(k) for k in KEEP)
    if lang != "zh-Hans" and not starts_with_name and first_src.isalpha() and first_src.isupper() and first_out.isalpha() and first_out.islower():
        errs.append("start with a capital letter, as the English does")
    if out.strip() == src.strip() and len(words(src)) >= 3:
        errs.append("left in English")
    if is_label(src):
        limit = max(len(src) * 1.4 + 4, 6) if lang == "zh-Hans" else max(len(src) * 2.2, len(src) + 14)
        if len(out) > limit:
            errs.append(f"too long for a short label ({len(out)} characters; keep it under {int(limit)})")
    return errs


def check_unit(u: Unit, lang: str, out: Any) -> list[str]:
    if not u.plural:
        return check_text(u, lang, u.en, out)  # type: ignore[arg-type]
    cats = LANGS[lang]["plurals"]
    if not isinstance(out, dict):
        return [f"a plural needs an object with the forms {cats}"]
    if sorted(out) != sorted(cats):
        return [f"give exactly the forms {cats}, you gave {sorted(out)}"]
    errs = []
    for c in cats:
        errs += [f"{c}: {e}" for e in check_text(u, lang, reference(u, lang, c), out[c], c)]
    return errs


def keep_space(src: str, out: str) -> str:
    """The translation with the English's leading and trailing whitespace."""
    lead = src[: len(src) - len(src.lstrip())]
    trail = src[len(src.rstrip()):]
    return lead + out.strip() + trail


def tidy(u: Unit, out: Any) -> Any:
    if u.plural and isinstance(out, dict):
        ref = u.en.get("other", "")  # type: ignore[union-attr]
        return {k: keep_space(ref, v) if isinstance(v, str) else v for k, v in out.items()}
    return keep_space(u.en, out) if isinstance(out, str) and isinstance(u.en, str) else out


def english_fill(u: Unit, lang: str) -> Any:
    """The English text in the shape the language needs (left English)."""
    if not u.plural:
        return u.en
    en = u.en
    assert isinstance(en, dict)
    return {c: reference(u, lang, c) for c in LANGS[lang]["plurals"]}


# ---------------------------------------------------------------------------- cache

class Cache:
    def __init__(self, lang: str):
        self.lang = lang
        self.path = CACHE_DIR / f"{lang}.json"
        self.lock = threading.Lock()
        data = json.loads(self.path.read_text(encoding="utf-8")) if self.path.exists() else {}
        self.entries: dict[str, dict[str, Any]] = data.get("entries", {})

    def get(self, u: Unit) -> dict[str, Any] | None:
        return self.entries.get(u.cache_key)

    def put(self, u: Unit, text: Any, state: str, why: str | None = None) -> None:
        with self.lock:
            e: dict[str, Any] = {"sha": u.sha, "state": state, "text": text}
            if why:
                e["why"] = why
            self.entries[u.cache_key] = e

    def save(self) -> None:
        with self.lock:
            self.path.parent.mkdir(parents=True, exist_ok=True)
            body = {"_about": "tools/i18n_translate.py cache: surface:key -> sha of the English, state "
                              "(model, manual, same, english, pending) and the text. 'manual' is never replaced.",
                    "lang": self.lang, "entries": dict(sorted(self.entries.items()))}
            tmp = self.path.with_suffix(".tmp")
            tmp.write_text(json.dumps(body, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
            tmp.replace(self.path)


# ---------------------------------------------------------------------------- outputs

def web_path(lang: str) -> Path:
    return WEB_EN.parent / f"{lang}.json"


def server_path(lang: str) -> Path:
    return SERVER_EN.parent / f"{lang}.json"


def android_out(src: Path, lang: str) -> Path:
    return src.parent.parent / f"values-{LANGS[lang]['android']}" / src.name


def read_existing(lang: str) -> dict[str, Any]:
    """What the output files hold now, keyed as the cache is (to take in hand edits)."""
    found: dict[str, Any] = {}
    for surface, path in (("web", web_path(lang)), ("server", server_path(lang))):
        if path.exists():
            for u in json_units(surface, json.loads(path.read_text(encoding="utf-8")),
                                skip_prefix=f"{servertexts.WEB_PREFIX}." if surface == "web" else None):
                found[u.cache_key] = u.en
    for src in android_files():
        p = android_out(src, lang)
        if not p.exists():
            continue
        mod = src.parts[-6]
        for e in ET.parse(p).getroot():
            if not isinstance(e.tag, str):
                continue
            k = f"android:{mod}:{e.get('name')}"
            if e.tag == "string":
                found[k] = android_decode(e.text or "")
            elif e.tag == "plurals":
                found[k] = {i.get("quantity"): android_decode(i.text or "") for i in e}
    return found


def rebuild(tree: dict, values: dict[str, Any], prefix: str = "", skip: str | None = None) -> dict:
    """`tree` (English, nested) with each text replaced by its translation; plural forms become the
    language's own forms, in the place of the English ones."""
    out: dict[str, Any] = {}
    done: set[str] = set()
    for k, v in tree.items():
        key = f"{prefix}{k}"
        if skip and key == skip:
            continue
        if isinstance(v, dict):
            out[k] = rebuild(v, values, f"{key}.", skip)
            continue
        m = PLURAL.search(k)
        if not m:
            out[k] = values.get(key, v)
            continue
        base = PLURAL.sub("", k)
        if base in done:
            continue
        done.add(base)
        forms = values.get(f"{prefix}{base}")
        if not isinstance(forms, dict):
            forms = {c: tree[f"{base}_{c}"] for c in CATEGORIES if f"{base}_{c}" in tree}
        for c in CATEGORIES:
            if c in forms:
                out[f"{base}_{c}"] = forms[c]
    return out


def write_outputs(lang: str, units: list[Unit], cache: Cache, surfaces: list[str]) -> list[Path]:
    by_surface: dict[str, dict[str, Any]] = {"web": {}, "server": {}, "android": {}}
    for u in units:
        e = cache.get(u)
        text = e["text"] if e and e["sha"] == u.sha or (e and e["state"] == "manual") else english_fill(u, lang)
        by_surface[u.surface][u.key] = text
    written: list[Path] = []

    def put(path: Path, text: str) -> None:
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
            written.append(path)

    if "server" in surfaces:
        tree = rebuild(json.loads(SERVER_EN.read_text(encoding="utf-8")), by_surface["server"])
        put(server_path(lang), json.dumps(tree, ensure_ascii=False, indent=2) + "\n")
    if "web" in surfaces:
        en = json.loads(WEB_EN.read_text(encoding="utf-8"))
        tree = rebuild(en, by_surface["web"], skip=servertexts.WEB_PREFIX)
        put(web_path(lang), servertexts.web_lang(tree, lang))
    if "android" in surfaces:
        for src in android_files():
            mod = src.parts[-6]
            lines = ['<?xml version="1.0" encoding="utf-8"?>', f"<!-- {OUT_HEADER} -->", "<resources>"]
            for e in ET.parse(src).getroot():
                if not isinstance(e.tag, str) or e.get("translatable") == "false":
                    continue
                name = e.get("name")
                text = by_surface["android"][f"{mod}:{src.name}:{name}"]
                if e.tag == "string":
                    lines.append(f'    <string name="{name}">{servertexts.android_text(text)}</string>')
                else:
                    lines.append(f'    <plurals name="{name}">')
                    for c in CATEGORIES:
                        if c in text:
                            lines.append(f'        <item quantity="{c}">{servertexts.android_text(text[c])}</item>')
                    lines.append("    </plurals>")
            lines += ["</resources>", ""]
            put(android_out(src, lang), "\n".join(lines))
    return written


# ---------------------------------------------------------------------------- the model

class Model:
    def __init__(self, endpoint: str, model: str | None, key: str | None):
        self.endpoint = endpoint.rstrip("/")
        self.key = key
        self.model = model or self._first_model()
        self.calls = 0
        self.tokens_out = 0

    def _req(self, path: str, body: dict | None = None, timeout: float = 600) -> dict:
        headers = {"Content-Type": "application/json", "User-Agent": "mailr-i18n-translate/1"}
        if self.key:
            headers["Authorization"] = f"Bearer {self.key}"
        data = json.dumps(body).encode() if body is not None else None
        req = urllib.request.Request(self.endpoint + path, data=data, headers=headers)
        with urllib.request.urlopen(req, timeout=timeout) as r:
            return json.loads(r.read())

    def _first_model(self) -> str:
        return self._req("/models", timeout=20)["data"][0]["id"]

    def chat(self, system: str, user: str) -> str:
        body = {"model": self.model, "temperature": 0.2, "max_tokens": 8192,
                "messages": [{"role": "system", "content": system}, {"role": "user", "content": user}],
                "chat_template_kwargs": {"enable_thinking": False}}
        last: Exception | None = None
        for attempt in range(4):
            try:
                r = self._req("/chat/completions", body)
                self.calls += 1
                self.tokens_out += (r.get("usage") or {}).get("completion_tokens", 0)
                return r["choices"][0]["message"]["content"] or ""
            except (urllib.error.URLError, TimeoutError, ConnectionError, KeyError, ValueError) as e:
                last = e
                time.sleep(5 * (attempt + 1))
        raise RuntimeError(f"the model endpoint failed four times: {type(last).__name__}")


