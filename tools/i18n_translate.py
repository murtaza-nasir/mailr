def system_prompt(lang: str) -> str:
    L = LANGS[lang]
    terms = "\n".join(f"- {en} → {tr}" for en, tr in L["terms"].items())
    return f"""You translate the user interface of mailr from British English into {L['name']}.
mailr is a self-hosted app for email, calendar, tasks and notes, used by small businesses, families
and self-hosters, with an assistant called Ambrose.

Style:
- {L['register']}
- Write natural {L['name']} as the major mail apps (Gmail, Outlook) do in their {L['name']} interface.
  Never translate word for word; keep the meaning and the plain, calm tone of the English.
- Short labels (buttons, menu items, tabs, column headings) stay short: one to three words.
- Keep the punctuation style of the English: a label without a full stop stays without one.

Never change:
- placeholders such as {{{{name}}}} and {{{{count}}}}, and format specifiers such as %1$s, %2$d, %d, %%:
  keep every one exactly as written (they may move within the sentence),
- markup such as <b>…</b>, <link>…</link>, <code>…</code>, <br/>: translate the text between the tags,
  keep the tags,
- URLs, email addresses, text in `backticks`, keyboard keys (Ctrl, Shift, Esc, Enter),
- these names: {', '.join(GLOSSARY['keep'][:20])} and other product names.
  Ambrose is the assistant's name (a person's name; {{{{name}}}} is often the assistant's name too).

Use these translations of the product's own terms every time:
{terms}

Input: a JSON object. Each id maps to {{"key": where the text is used, "en": the English}}. The key
tells you the screen and the role (a button, a title, an error); use it to choose the right word
(for example a verb on a button, a noun on a folder).
For a plural, "en" is an object of English forms and "forms" lists the forms to return
({', '.join(L['plurals'])}); answer with an object with exactly those forms.
An item may carry "note" (follow it) or "fix": the problem with an earlier answer; correct it.

Output: only a JSON object mapping each id to its translation (a string, or an object for a
plural). No comments, no code fences."""


def parse_json(s: str) -> dict:
    s = s.strip()
    s = re.sub(r"^```(?:json)?\s*|\s*```$", "", s)
    a, b = s.find("{"), s.rfind("}")
    if a < 0 or b < 0:
        raise ValueError("no JSON object")
    return json.loads(s[a:b + 1])


def batches(units: list[Unit], size: int, chars: int) -> list[list[Unit]]:
    out: list[list[Unit]] = []
    cur: list[Unit] = []
    n = 0
    area = None
    for u in units:
        a = (u.surface, u.key.split(".")[0] if u.surface != "android" else u.key.split(":")[1])
        length = sum(len(t) for t in u.texts())
        if cur and (len(cur) >= size or n + length > chars or a != area):
            out.append(cur)
            cur, n = [], 0
        cur.append(u)
        n += length
        area = a
    if cur:
        out.append(cur)
    return out


def translate_batch(model: Model, lang: str, items: list[Unit], fixes: dict[str, str]) -> dict[str, Any]:
    payload: dict[str, Any] = {}
    for i, u in enumerate(items, 1):
        item: dict[str, Any] = {"key": u.key.split(":", 2)[-1] if u.surface == "android" else u.key, "en": u.en}
        if u.plural:
            item["forms"] = LANGS[lang]["plurals"]
            if lang in ("ru", "fr", "pt-BR") and "one" in item["forms"]:
                covers = "21, 31, 101…" if lang == "ru" else "0 as well as 1"
                item["note"] = (f"In {LANGS[lang]['name']} the 'one' form also covers {covers}: write it with the "
                                "number placeholder, like the English 'other' form, even where the English 'one' has none.")
        if ".step." in u.key and u.surface == "server":
            item["note"] = ("A progress line shown while Ambrose works on it. Use one progressive form for all of them: "
                            + STEP_STYLE.get(lang, "the language's usual 'doing X' form") + ".")
        if u.cache_key in fixes:
            item["fix"] = fixes[u.cache_key]
        payload[str(i)] = item
    raw = model.chat(system_prompt(lang), json.dumps(payload, ensure_ascii=False))
    try:
        got = parse_json(raw)
    except ValueError:
        return {}
    return {u.cache_key: got.get(str(i)) for i, u in enumerate(items, 1)}


# ---------------------------------------------------------------------------- the run

@dataclass
class Stats:
    total: int = 0
    kept: int = 0
    model: int = 0
    reused: int = 0
    same: int = 0
    manual: int = 0
    english: list[str] = field(default_factory=list)
    adopted: int = 0
    seconds: float = 0.0


def adopt_hand_edits(lang: str, units: list[Unit], cache: Cache) -> int:
    """Texts edited in an output file since the last run become `manual` entries."""
    existing = read_existing(lang)
    n = 0
    for u in units:
        have = existing.get(u.cache_key)
        if have is None:
            continue
        e = cache.get(u)
        if e is None:
            continue
        if e["state"] == "manual":
            if have != e["text"]:
                cache.put(u, have, "manual")
                n += 1
            continue
        if e["sha"] != u.sha or e["state"] == "pending":
            continue
        if have != e["text"] and have != english_fill(u, lang):
            cache.put(u, have, "manual")
            n += 1
    return n


def todo_units(units: list[Unit], cache: Cache, retry_english: bool, retranslate: list[str],
               retranslate_prefix: list[str] = ()) -> list[Unit]:
    out = []
    for u in units:
        e = cache.get(u)
        if e and e["state"] == "manual":
            continue
        if any(u.cache_key.startswith(p) for p in retranslate_prefix) and e and e["state"] != "same":
            out.append(u)
            continue
        if e and e["sha"] == u.sha and e["state"] != "pending" and not (retry_english and e["state"] == "english"):
            if not any(t.lower() in " ".join(u.texts()).lower() for t in retranslate) or e["state"] == "same":
                continue
        out.append(u)
    return out


def run_language(lang: str, units: list[Unit], args: argparse.Namespace, model: Model | None, surfaces: list[str]) -> Stats:
    t0 = time.time()
    st = Stats(total=len(units))
    cache = Cache(lang)
    st.adopted = adopt_hand_edits(lang, units, cache)
    todo = todo_units(units, cache, args.retry_english, args.retranslate_term or [], args.retranslate_prefix or [])
    st.kept = len(units) - len(todo)

    if args.offline:
        for u in todo:
            cache.put(u, english_fill(u, lang), "pending")
        todo = []

    # Nothing to translate, or the same long English already translated elsewhere.
    memory: dict[str, Any] = {}
    for u in units:
        e = cache.get(u)
        if e and e["sha"] == u.sha and e["state"] in ("model", "manual") and not u.plural and len(words(u.en)) >= 3:  # type: ignore[arg-type]
            memory[json.dumps([u.surface == "android", u.en], ensure_ascii=False)] = e["text"]
    rest = []
    for u in todo:
        if not needs_model(u):
            cache.put(u, english_fill(u, lang), "same")
            st.same += 1
            continue
        forced = any(u.cache_key.startswith(p) for p in (args.retranslate_prefix or []))
        hit = None if u.plural or forced else memory.get(json.dumps([u.surface == "android", u.en], ensure_ascii=False))
        if hit is not None and not check_unit(u, lang, hit):
            cache.put(u, hit, "model")
            st.reused += 1
            continue
        rest.append(u)
    if args.limit:
        rest = rest[: args.limit]

    if rest and model is None:
        raise SystemExit("no model endpoint")
    fixes: dict[str, str] = {}
    pending = rest
    for attempt in range(3):
        if not pending:
            break
        size = args.batch if attempt == 0 else max(4, args.batch // 4)
        groups = batches(pending, size, args.chars)
        failed: list[Unit] = []
        done = 0
        with ThreadPoolExecutor(max_workers=args.concurrency) as pool:
            futs = {pool.submit(translate_batch, model, lang, g, fixes): g for g in groups}  # type: ignore[arg-type]
            for f in as_completed(futs):
                g = futs[f]
                try:
                    got = f.result()
                except RuntimeError as e:
                    cache.save()
                    raise SystemExit(f"{lang}: {e}; stopped (the cache keeps what is done)")
                for u in g:
                    out = tidy(u, got.get(u.cache_key))
                    errs = check_unit(u, lang, out)
                    if errs:
                        fixes[u.cache_key] = "; ".join(errs)[:400]
                        failed.append(u)
                    else:
                        cache.put(u, out, "model")
                        fixes.pop(u.cache_key, None)
                        st.model += 1
                done += 1
                if done % 10 == 0:
                    cache.save()
                    print(f"  {lang}: round {attempt + 1}, {done}/{len(groups)} batches, {len(failed)} to retry", flush=True)
        cache.save()
        pending = failed
    for u in pending:
        cache.put(u, english_fill(u, lang), "english", fixes.get(u.cache_key))
        st.english.append(f"{u.cache_key}: {fixes.get(u.cache_key, '')}")
    cache.save()
    write_outputs(lang, units, cache, surfaces)
    st.manual = sum(1 for u in units if (cache.get(u) or {}).get("state") == "manual")
    st.seconds = time.time() - t0
    return st


def check(langs: list[str], units: list[Unit], surfaces: list[str]) -> int:
    bad = 0
    for lang in langs:
        cache = Cache(lang)
        missing, stale, pending, english, manual_stale = [], [], [], [], []
        for u in units:
            e = cache.get(u)
            if e is None:
                missing.append(u.cache_key)
            elif e["state"] == "manual":
                if e["sha"] != u.sha:
                    manual_stale.append(u.cache_key)
            elif e["sha"] != u.sha:
                stale.append(u.cache_key)
            elif e["state"] == "pending":
                pending.append(u.cache_key)
            elif e["state"] == "english":
                english.append(u.cache_key)
        existing = read_existing(lang)
        edits = [u.cache_key for u in units if (e := cache.get(u)) and e["sha"] == u.sha and e["state"] != "manual"
                 and u.cache_key in existing and existing[u.cache_key] != e["text"]
                 and existing[u.cache_key] != english_fill(u, lang)]
        print(f"{lang}: {len(units)} texts; missing {len(missing)}, stale {len(stale)}, pending {len(pending)}, "
              f"left English {len(english)}, hand edits to take in {len(edits)}, hand edits whose English changed {len(manual_stale)}")
        for name, keys in (("missing", missing), ("stale", stale), ("pending", pending),
                           ("hand edit, English changed", manual_stale)):
            for k in keys[:20]:
                print(f"  {name}: {k}")
            if len(keys) > 20:
                print(f"  … and {len(keys) - 20} more {name}")
        if missing or stale or pending or manual_stale:
            bad = 1
    return bad


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--lang", default=",".join(LANGS), help="comma-separated tags (default: every language in the glossary)")
    ap.add_argument("--surface", default="web,server,android")
    ap.add_argument("--check", action="store_true", help="no model; exit 1 when a text is missing or stale")
    ap.add_argument("--offline", action="store_true", help="no model; new texts are filled with English as pending")
    ap.add_argument("--write", action="store_true", help="no model; take in hand edits, then rewrite the outputs from the cache")
    ap.add_argument("--retry-english", action="store_true", help="try again the texts left English")
    ap.add_argument("--retranslate-prefix", action="append", help="translate again the texts whose cache key starts with this (manual ones too)")
    ap.add_argument("--retranslate-term", action="append", help="translate again texts containing this English term")
    ap.add_argument("--endpoint", default=os.environ.get("MAILR_I18N_ENDPOINT"),
                    help="OpenAI-compatible base URL, e.g. http://localhost:8000/v1 (or set MAILR_I18N_ENDPOINT)")
    ap.add_argument("--model", default=os.environ.get("MAILR_I18N_MODEL"))
    ap.add_argument("--concurrency", type=int, default=2, help="requests in flight (at most 4)")
    ap.add_argument("--batch", type=int, default=40, help="texts per request")
    ap.add_argument("--chars", type=int, default=3000, help="English characters per request")
    ap.add_argument("--limit", type=int, default=0, help="translate at most this many texts per language (testing)")
    args = ap.parse_args()
    args.concurrency = max(1, min(args.concurrency, 4))
    langs = [x for x in args.lang.split(",") if x]
    for lang in langs:
        if lang not in LANGS:
            raise SystemExit(f"{lang} is not in {GLOSSARY_FILE.relative_to(ROOT)}")
    surfaces = [x for x in args.surface.split(",") if x]
    units = load_units(surfaces)
    if args.check:
        return check(langs, units, surfaces)
    if args.write:
        for lang in langs:
            cache = Cache(lang)
            n = adopt_hand_edits(lang, units, cache)
            cache.save()
            write_outputs(lang, units, cache, surfaces)
            print(f"{lang}: {n} hand edits taken in")
        return servertexts.main([])
    model = None
    if not args.offline:
        if not args.endpoint:
            raise SystemExit("no model endpoint: pass --endpoint http://<host>:<port>/v1 or set MAILR_I18N_ENDPOINT "
                             "(any OpenAI-compatible server). --check, --offline and --write need no model.")
        model = Model(args.endpoint, args.model, os.environ.get("MAILR_I18N_API_KEY"))
        print(f"model {model.model} at {model.endpoint}", flush=True)
    for lang in langs:
        st = run_language(lang, units, args, model, surfaces)
        print(f"{lang}: {st.total} texts in {st.seconds:.0f} s: {st.kept} already done, {st.model} by the model, "
              f"{st.reused} reused, {st.same} need no translation, {st.manual} hand-made, "
              f"{st.adopted} hand edits taken in, {len(st.english)} left English", flush=True)
        for line in st.english:
            print(f"  left English: {line}")
    if model:
        print(f"{model.calls} requests, {model.tokens_out} tokens out")
    return servertexts.main([])


if __name__ == "__main__":
    sys.exit(main())
