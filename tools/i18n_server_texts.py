#!/usr/bin/env python3
"""The apps' copy of the server texts they render themselves ("texts kept as a key").

Approval cards, their outcomes and the assistant's tool steps carry catalogue keys (`approvals.*` in
backend/mailr/i18n/en.json) beside their English. The web and Android apps render those keys with
their own t(), so the words follow the app's language. This script copies the sections into:

- frontend/src/locales/en.json, under `serverText.<section>` (the web's other languages translate
  them there, like any web text);
- frontend/src/features/rail/assistant/present/serverKeys.ts, the server key → web key map (the
  build gives every key it finds in the code a short ID, so each key is named once, literally);
- android/app/src/main/res/values/strings_server.xml (`srv_<key>`, `{{name}}` placeholders kept);
- android/app/src/main/java/io/github/murtazanasir/mailr/ui/present/ServerKeys.kt, the key → resource map.

For every other language with a server catalogue (backend/mailr/i18n/<lang>.json, written by
tools/i18n_translate.py) it also writes the same sections into frontend/src/locales/<lang>.json
(when that file exists) and android/app/src/main/res/values-<qualifier>/strings_server.xml.

    tools/i18n_server_texts.py           write the copies
    tools/i18n_server_texts.py --check   change nothing; exit 1 when a copy is out of date

The server catalogue is the source: edit English there, then run this (tools/generate runs --check).
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parent.parent
SERVER = ROOT / "backend/mailr/i18n/en.json"
SECTIONS = ("approvals",)
WEB_EN = ROOT / "frontend/src/locales/en.json"
WEB_PREFIX = "serverText"
WEB_KEYS = ROOT / "frontend/src/features/rail/assistant/present/serverKeys.ts"
ANDROID_XML = ROOT / "android/app/src/main/res/values/strings_server.xml"
GLOSSARY = ROOT / "tools/i18n/glossary.json"
ANDROID_KT = ROOT / "android/app/src/main/java/io/github/murtazanasir/mailr/ui/present/ServerKeys.kt"
PLURAL = re.compile(r"_(zero|one|two|few|many|other)$")
HEADER = "Generated by tools/i18n_server_texts.py from backend/mailr/i18n/en.json. Do not edit."


def flatten(d: dict, prefix: str = "") -> dict[str, str]:
    out: dict[str, str] = {}
    for k, v in d.items():
        if isinstance(v, dict):
            out.update(flatten(v, f"{prefix}{k}."))
        else:
            out[f"{prefix}{k}"] = str(v)
    return out


def server_texts(lang: str = "en") -> tuple[dict, dict[str, str]]:
    path = SERVER if lang == "en" else SERVER.parent / f"{lang}.json"
    if not path.exists():
        path = SERVER
    cat = json.loads(path.read_text(encoding="utf-8"))
    tree = {s: cat[s] for s in SECTIONS}
    return tree, flatten(tree)


def other_languages() -> list[str]:
    """The languages with a server catalogue besides English."""
    return sorted(p.stem for p in SERVER.parent.glob("*.json")
                  if p.stem != "en" and re.fullmatch(r"[A-Za-z]{2,3}(-[A-Za-z0-9]{2,8})*", p.stem))


def android_qualifier(lang: str) -> str:
    """The resource qualifier of a language (tools/i18n/glossary.json), "pt-BR" → "pt-rBR"."""
    langs = json.loads(GLOSSARY.read_text(encoding="utf-8"))["languages"] if GLOSSARY.exists() else {}
    if lang in langs:
        return langs[lang]["android"]
    return "b+" + lang.replace("-", "+") if "-" in lang else lang


def web_lang(tree: dict, lang: str) -> str:
    """A web locale file (`tree`, without or with its serverText) with the server's texts in `lang`."""
    web = dict(tree)
    web[WEB_PREFIX] = server_texts(lang)[0]
    web = dict(sorted(web.items()))
    return json.dumps(web, ensure_ascii=False, indent=2) + "\n"


def web_en(tree: dict) -> str:
    web = json.loads(WEB_EN.read_text(encoding="utf-8"))
    web[WEB_PREFIX] = tree
    web = dict(sorted(web.items()))
    return json.dumps(web, ensure_ascii=False, indent=2) + "\n"


def bases(flat: dict[str, str]) -> list[str]:
    return sorted({PLURAL.sub("", k) for k in flat})


def web_keys(flat: dict[str, str]) -> str:
    lines = [f"// {HEADER}", "// The server key of a card's text → the web key that holds it.", "",
             "export const SERVER_KEYS: Record<string, string> = {"]
    lines += [f"  '{b}': '{WEB_PREFIX}.{b}'," for b in bases(flat)]
    lines += ["}", ""]
    return "\n".join(lines)


def res_name(key: str) -> str:
    return "srv_" + re.sub(r"[^A-Za-z0-9_]", "_", key)


def android_text(v: str) -> str:
    v = escape(v).replace("\\", "\\\\").replace("'", "\\'").replace('"', '\\"').replace("\n", "\\n")
    return "\\" + v if v[:1] in ("@", "?") else v


def android_xml(flat: dict[str, str], header: str = HEADER) -> str:
    out = ['<?xml version="1.0" encoding="utf-8"?>', f"<!-- {header} -->",
           "<resources>"]
    names: dict[str, str] = {}
    for b in bases(flat):
        n = res_name(b)
        if n in names:
            raise SystemExit(f"{b} and {names[n]} give the same resource name {n}")
        names[n] = b
        forms = {PLURAL.search(k)[1]: v for k, v in flat.items() if PLURAL.sub("", k) == b and PLURAL.search(k)}
        if forms:
            out.append(f'    <plurals name="{n}">')
            for q in ("zero", "one", "two", "few", "many", "other"):
                if q in forms:
                    out.append(f'        <item quantity="{q}">{android_text(forms[q])}</item>')
            out.append("    </plurals>")
        else:
            out.append(f'    <string name="{n}">{android_text(flat[b])}</string>')
    out += ["</resources>", ""]
    return "\n".join(out)


def android_kt(flat: dict[str, str]) -> str:
    strings, plurals = [], []
    for b in bases(flat):
        (plurals if b not in flat else strings).append(b)
    lines = ["package io.github.murtazanasir.mailr.ui.present", "", "import io.github.murtazanasir.mailr.R", "", f"// {HEADER}",
             "", "/** The server key of a card's text → the string or plurals resource that holds it */",
             "internal object ServerKeys {"]
    lines.append("    val strings: Map<String, Int> by lazy {")
    lines.append("        hashMapOf(")
    lines += [f'            "{b}" to R.string.{res_name(b)},' for b in strings]
    lines += ["        )", "    }", "", "    val plurals: Map<String, Int> by lazy {", "        hashMapOf("]
    lines += [f'            "{b}" to R.plurals.{res_name(b)},' for b in plurals]
    lines += ["        )", "    }", "}", ""]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    check = "--check" in (sys.argv[1:] if argv is None else argv)
    tree, flat = server_texts()
    want = {WEB_EN: web_en(tree), WEB_KEYS: web_keys(flat), ANDROID_XML: android_xml(flat), ANDROID_KT: android_kt(flat)}
    for lang in other_languages():
        web = WEB_EN.parent / f"{lang}.json"
        if web.exists():
            want[web] = web_lang(json.loads(web.read_text(encoding="utf-8")), lang)
        xml = ANDROID_XML.parent.parent / f"values-{android_qualifier(lang)}" / ANDROID_XML.name
        want[xml] = android_xml(server_texts(lang)[1], HEADER.replace("en.json", f"{lang}.json"))
    stale = [p for p, text in want.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
    if check:
        for p in stale:
            print(f"i18n server texts: {p.relative_to(ROOT)} is out of date (run tools/i18n_server_texts.py)")
        return 1 if stale else 0
    for p in stale:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(want[p], encoding="utf-8")
        print(f"wrote {p.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
